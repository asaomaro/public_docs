def pick(names):
    """埋め込む分だけ {name: {d, a}} にする。"""
    return {n: {"d": ICONS[n][1], "a": ICONS[n][2]} for n in names if n in ICONS}


def used_in(text):
    """台本・文書の文字列の中で、アイコンの名前として出てくるもの（"name" の形）。"""
    if len(text) > 1 << 20:   # 埋め込みの声・画像（data:…）を先に除く。100MB の台本で、名前ごとに全文を探すと 5 秒かかった
        text = re.sub(r'"data:[^"]*"', '""', text)
    return [n for n in ICONS if ('"%s"' % n) in text or ("'%s'" % n) in text]


def svg(name, size=24, cls="ico", extra=""):
    """インラインの SVG（md-to-doc の部品で使う）。色は currentColor。"""
    if name not in ICONS:
        return ""
    paths = "".join('<path d="%s"/>' % d for d in ICONS[name][1])
    return ('<svg class="%s" data-ico="%s" data-ico-anim="%s" viewBox="0 0 24 24" width="%d" height="%d" fill="none" stroke="currentColor" '
            'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"%s>%s</svg>'
            % (cls, name, ICONS[name][2], size, size, extra, paths))


